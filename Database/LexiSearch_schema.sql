BEGIN TRANSACTION;
CREATE TABLE IF NOT EXISTS "Cart" (
	"cartID"	INTEGER NOT NULL,
	"userID"	INTEGER NOT NULL UNIQUE,
	"createdAt"	TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY("cartID" AUTOINCREMENT),
	FOREIGN KEY("userID") REFERENCES "User"("userID")
);
CREATE TABLE IF NOT EXISTS "CartItem" (
	"cartItemID"	INTEGER NOT NULL,
	"cartID"	INTEGER NOT NULL,
	"productID"	INTEGER NOT NULL,
	"quantity"	INTEGER NOT NULL,
	PRIMARY KEY("cartItemID" AUTOINCREMENT),
	FOREIGN KEY("cartID") REFERENCES "Cart"("cartID"),
	FOREIGN KEY("productID") REFERENCES "Product"("productID")
);
CREATE TABLE IF NOT EXISTS "Inventory" (
	"inventoryID"	INTEGER NOT NULL,
	"productID"	INTEGER NOT NULL UNIQUE,
	"quantity"	INTEGER NOT NULL,
	"lastUpdated"	TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	PRIMARY KEY("inventoryID" AUTOINCREMENT),
	FOREIGN KEY("productID") REFERENCES "Product"("productID")
);
CREATE TABLE IF NOT EXISTS "Keyword" (
	"keywordID"	INTEGER NOT NULL,
	"keyword"	TEXT NOT NULL UNIQUE,
	PRIMARY KEY("keywordID" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "OrderItem" (
	"orderItemID"	INTEGER NOT NULL,
	"orderID"	INTEGER NOT NULL,
	"productID"	INTEGER NOT NULL,
	"quantity"	INTEGER NOT NULL,
	"price"	REAL NOT NULL,
	PRIMARY KEY("orderItemID" AUTOINCREMENT),
	FOREIGN KEY("orderID") REFERENCES "Orders"("orderID"),
	FOREIGN KEY("productID") REFERENCES "Product"("productID")
);
CREATE TABLE IF NOT EXISTS "Orders" (
	"orderID"	INTEGER NOT NULL,
	"userID"	INTEGER NOT NULL,
	"orderDate"	TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	"totalAmount"	REAL NOT NULL,
	"status"	TEXT NOT NULL,
	PRIMARY KEY("orderID" AUTOINCREMENT),
	FOREIGN KEY("userID") REFERENCES "User"("userID")
);
CREATE TABLE IF NOT EXISTS "Product" (
	"productID"	INTEGER NOT NULL,
	"name"	TEXT NOT NULL,
	"category"	TEXT NOT NULL,
	"color"	TEXT NOT NULL,
	"size"	TEXT NOT NULL,
	"price"	REAL NOT NULL,
	"description"	TEXT,
	"brand"	TEXT NOT NULL,
	PRIMARY KEY("productID" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "ProductKeyword" (
	"productID"	INTEGER NOT NULL,
	"keywordID"	INTEGER NOT NULL,
	PRIMARY KEY("productID","keywordID"),
	FOREIGN KEY("keywordID") REFERENCES "Keyword"("keywordID"),
	FOREIGN KEY("productID") REFERENCES "Product"("productID")
);
CREATE TABLE IF NOT EXISTS "User" (
	"userID"	INTEGER NOT NULL,
	"firstName"	TEXT NOT NULL,
	"lastName"	TEXT NOT NULL,
	"email"	TEXT NOT NULL UNIQUE,
	"password"	TEXT NOT NULL,
	"role"	TEXT NOT NULL,
	PRIMARY KEY("userID" AUTOINCREMENT)
);
COMMIT;
